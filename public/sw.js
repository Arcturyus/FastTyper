/**
 * Service worker « network-first » avec repli hors-ligne. FastTyper est déjà
 * 100 % local (données en IndexedDB) : on veut surtout que l'app se lance sans
 * réseau. On sert le réseau en priorité (pour rester à jour) et on met en cache
 * au passage ; hors-ligne, on répond depuis le cache, et toute navigation
 * retombe sur index.html.
 */
const CACHE = "fasttyper-v1";

self.addEventListener("install", () => self.skipWaiting());

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET" || new URL(req.url).origin !== self.location.origin) return;
  event.respondWith(
    fetch(req)
      .then((res) => {
        const copy = res.clone();
        caches.open(CACHE).then((c) => c.put(req, copy)).catch(() => {});
        return res;
      })
      .catch(async () => {
        const cached = await caches.match(req);
        if (cached) return cached;
        if (req.mode === "navigate") {
          const shell = await caches.match("/index.html");
          if (shell) return shell;
        }
        return Response.error();
      })
  );
});
